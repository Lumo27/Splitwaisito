export function traduzir(idioma: Idioma, chave: string): string {
  return traducciones[idioma][chave] ?? traducciones.es[chave] ?? chave
}

export function useTraduccion() {
  const idioma = useAppStore((state) => state.preferencias.language)

  return (clave: string) => traduzir(idioma, clave)
}
